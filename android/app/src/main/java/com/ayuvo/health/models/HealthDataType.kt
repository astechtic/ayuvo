package com.ayuvo.health.models

/**
 * Health Data hub metric registry — the Android mirror of `shared/health/metric_registry.json`
 * (parity-tested by HealthDataTypeContractTest; the entry block below is generated from that
 * file and must be regenerated, never hand-edited, when the contract changes). Pure Kotlin:
 * nothing here may import androidx or Compose so the sync engine and its JVM tests stay
 * framework-free.
 *
 * Conventions shared with iOS: percent stored 0–100, durations in seconds, SI-ish units,
 * unknown native types stored under their raw id in category `other`.
 */
enum class HealthCategory(val id: String) {
    ACTIVITY("activity"),
    BODY("body"),
    CYCLE_TRACKING("cycle_tracking"),
    HEARING("hearing"),
    HEART("heart"),
    MENTAL_WELLBEING("mental_wellbeing"),
    MOBILITY("mobility"),
    NUTRITION("nutrition"),
    RESPIRATORY("respiratory"),
    SLEEP("sleep"),
    SYMPTOMS("symptoms"),
    VITALS("vitals"),
    OTHER("other");

    companion object {
        fun byId(id: String): HealthCategory? = entries.firstOrNull { it.id == id }
    }
}

enum class HealthKind(val id: String) {
    CUMULATIVE("cumulative"), DISCRETE("discrete"), DURATION("duration"),
    CATEGORY("category"), SESSION("session"), SERIES("series");

    companion object {
        fun byId(id: String): HealthKind? = entries.firstOrNull { it.id == id }
    }
}

enum class HealthAggregation { SUM, DURATION, AVERAGE, MIN_MAX, LATEST, COUNT }

enum class HealthDayAttribution(val id: String) {
    START("start"), END("end"), SPAN("span")
}

enum class HealthAndroidTier { CORE, EXTENDED }

/**
 * Platform feature gates; mapped to `HealthConnectFeatures` constants only inside the manager.
 * [registryName] is the constant name the shared registry uses for `hc_feature_flag`.
 */
enum class HealthFeatureFlag(val registryName: String) {
    HISTORY("FEATURE_READ_HEALTH_DATA_HISTORY"),
    SKIN_TEMPERATURE("FEATURE_SKIN_TEMPERATURE"),
    PLANNED_EXERCISE("FEATURE_PLANNED_EXERCISE"),
    MINDFULNESS("FEATURE_MINDFULNESS_SESSION")
}

