    /** True when connect-client 1.1.0 can read this type on Android (reserved types are not). */
    val sdkAvailable: Boolean get() = hcRecord != null && hcPermission != null && !reserved

    val isSumType: Boolean get() = aggregation == HealthAggregation.SUM && kind == HealthKind.CUMULATIVE

    /** Day totals come from Health Connect's priority-deduplicated aggregate instead of local sums. */
    val usesPlatformAggregate: Boolean
        get() = sdkAvailable && this in PLATFORM_AGGREGATE_TYPES

    val isSeriesType: Boolean get() = kind == HealthKind.SERIES

    val isDurationLike: Boolean
        get() = aggregation == HealthAggregation.DURATION || kind == HealthKind.SESSION || kind == HealthKind.DURATION

    /** Virtual nutrition roll-ups derived from `nutrition.extra_json` on Android. */
    val isVirtualDietary: Boolean get() = id.startsWith("dietary_")

    /** Humanised fallback label when no string resource exists (e.g. imported raw ids). */
    fun displayFallback(): String = humanise(id)

    companion object {
        const val REGISTRY_VERSION = 1

        val canonicalUnits: Set<String> = setOf(
            "count", "m", "kcal", "kcal/d", "count/min", "ms", "%", "degC", "mmHg", "mmol/L", "kg", "s", "L",
            "mL", "g", "mg", "mcg", "m/s", "W", "dBASPL", "mL/min·kg", "kcal/hr·kg", "count/hr", "IU", "L/min",
            "mcS", "days", "none"
        )

        private val byIdMap: Map<String, HealthDataType> by lazy { entries.associateBy { it.id } }

        fun byId(id: String): HealthDataType? = byIdMap[id]

        val sdkTypes: List<HealthDataType> by lazy { entries.filter { it.sdkAvailable } }

        val coreTypes: List<HealthDataType> by lazy { sdkTypes.filter { it.androidTier == HealthAndroidTier.CORE } }

        val extendedTypes: List<HealthDataType> by lazy { sdkTypes.filter { it.androidTier == HealthAndroidTier.EXTENDED } }

        fun forCategory(category: HealthCategory): List<HealthDataType> = entries.filter { it.category == category }

        /** Types whose daily total Health Connect aggregates for us (priority-deduped across sources). */
        val PLATFORM_AGGREGATE_TYPES: Set<HealthDataType> by lazy {
            setOf(STEPS, DISTANCE, ACTIVE_ENERGY, TOTAL_ENERGY, FLOORS_CLIMBED, ELEVATION_GAINED, HYDRATION, WHEELCHAIR_PUSHES, WORKOUT)
        }

        /** `dietary_*` slug → key inside `nutrition.extra_json`. */
        val dietaryExtraKeys: Map<HealthDataType, String> by lazy {
            entries.filter { it.isVirtualDietary }.associateWith { it.id.removePrefix("dietary_") }
        }

        fun humanise(slug: String): String = slug
            .removePrefix("symptom_")
            .split('_')
            .filter { it.isNotBlank() }
            .joinToString(" ") { part -> part.replaceFirstChar { c -> c.uppercaseChar() } }
    }
